const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const window = {};
vm.runInNewContext(fs.readFileSync('assets/js/news-automation-health.js','utf8'), {window});
const h = window.NewsAutomationHealth;
const config = JSON.parse(fs.readFileSync('config/news-automation.json','utf8'));
const ms = x => new Date(x).getTime();
assert.equal(h.latestSlot(config, ms('2026-10-10T00:10:00Z')),ms('2026-10-09T14:20:00Z'));
assert.equal(h.latestSlot(config, ms('2026-10-10T00:30:00Z')),ms('2026-10-10T00:20:00Z'));
assert.equal(h.latestSlot(config, ms('2026-10-10T13:05:00Z')),ms('2026-10-10T12:20:00Z'));
const feeds = Array.from({length:16}, (_,i)=>({source_id:'source-'+i,status:'parsed',new:0,skipped:4,filtered:1,duplicates:3}));
const good = {checked_at:'2026-10-10T12:27:00Z', feeds_configured:16, feeds_fetched:16,
 accepted_new:0, article_total:263, feed_status:feeds, fetch_errors:[]};
let state = h.evaluate(good, config, ms('2026-10-10T13:20:00Z'));
assert.equal(state.state,'healthy','zero new articles are not an outage');
assert.equal(state.parsed,16);
assert.equal(state.duplicate,48);
assert.equal(state.filtered,16);
const old = {...good,checked_at:'2026-10-10T10:40:00Z'};
state = h.evaluate(old,config,ms('2026-10-10T14:00:00Z'));
assert.equal(state.state,'stale','last scheduled check overdue beyond grace period');
state = h.evaluate({...good,checked_at:'2026-10-10T14:35:00Z'},config,ms('2026-10-10T23:00:00Z'));
assert.equal(state.state,'healthy','overnight pause is scheduled, not overdue');
const warning = {...good,feed_status:feeds.map((item,i)=>i===8?{...item,status:'empty-feed'}:item)};
state = h.evaluate(warning,config,ms('2026-10-10T13:20:00Z'));
assert.equal(state.state,'degraded','HTTP 200 with empty feed must warn');
assert.equal(state.empty.length,1);
state = h.evaluate({...good,fetch_errors:[{source_id:'test',error:'Timeout'}]},config,ms('2026-10-10T13:20:00Z'));
assert.equal(state.state,'degraded','fetch failures are visible even when other sources are valid');
state = h.evaluate({},config,ms('2026-10-10T13:20:00Z'));
assert.equal(state.state,'no-data','never claim healthy without real health report');
console.log('PASS RSS maintenance: timely, missing slot, overnight, empty source, failures and no-new are distinct');
